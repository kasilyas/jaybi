// Audit isolé : vrais handlers compilés, stockage entièrement simulé, aucune connexion DB.
import assert from 'node:assert/strict';
process.env.NODE_ENV = 'test';
process.env.DEV_BYPASS = 'false';
process.env.DATABASE_URL = 'postgresql://unused:unused@127.0.0.1:1/unused';
const { prisma } = await import('../backend/dist/lib/prisma.js');
const { ordersRouter } = await import('../backend/dist/routes/orders.routes.js');
const { productsRouter } = await import('../backend/dist/routes/products.routes.js');
const { sendOtpEmail } = await import('../backend/dist/lib/otp.js');
const { matchProduct } = await import('../backend/dist/scraping/matcher.js');
const handler = (router, method, path) => router.stack.find(s => s.route?.path === path && s.route.methods[method]).route.stack.at(-1).handle;
const orderHandler = handler(ordersRouter, 'post', '/');
const response = () => ({ statusCode: 200, status(n) { this.statusCode = n; return this; }, json(body) { this.body = body; return this; } });
const user = { sub: 'audit-user', email: 'audit@example.test', role: 'customer' };
const product = { id: 'p1', name: 'Produit audit', isActive: false, isDeleted: false, discountPercent: 25, prices: [{ price: 100, storeId: 's1', city: 'Rabat', available: false, store: { name: 'Audit', isActive: false, isDeleted: true } }] };
prisma.product.findMany = async () => [product];
prisma.pack.findMany = async () => [{ id: 'unrelated-pack', discountPercent: 90, products: [], expiresAt: new Date('2020-01-01') }];
prisma.auditLog.create = async () => ({});
prisma.order.create = async ({ data }) => ({ ...data, id: 'audit-order', createdAt: new Date(), items: data.items.create });
prisma.$transaction = async fn => fn(prisma);
const create = async (item, promoCodeId) => {
  const res = response();
  await orderHandler({ user, body: { items: [item], promoCodeId } }, res);
  return res;
};
await assert.rejects(sendOtpEmail('audit@example.test', '654321'), /SMTP not configured/);
console.log('CONFIRME: envoi OTP impossible hors bypass.');
const discounted = await create({ productId: 'p1', quantity: 1, packId: 'unrelated-pack' });
assert.equal(discounted.body.total, 10);
console.log('CONFIRME: pack sans produit et expiré applique 90% de remise à un autre produit (100 -> 10).');
const inactive = await create({ productId: 'p1', quantity: 1 });
assert.equal(inactive.statusCode, 201);
assert.equal(inactive.body.total, 100);
console.log('CONFIRME: commande acceptée pour produit inactif, prix indisponible, enseigne supprimée; remise produit 25% ignorée.');
let uses = 0;
prisma.promoCode.findUnique = async () => ({ id: 'promo', code: 'AUDIT', isActive: true, isDeleted: false, currentUses: uses, maxUses: 1, startsAt: new Date('2020-01-01'), expiresAt: new Date('2099-01-01'), discountType: 'percent', discountValue: 10 });
prisma.promoCode.update = async () => { uses++; return {}; };
const concurrent = await Promise.all([create({ productId: 'p1', quantity: 1 }, 'promo'), create({ productId: 'p1', quantity: 1 }, 'promo')]);
assert.equal(uses, 2);
assert.ok(concurrent.every(r => r.body.discountAmount === 10));
console.log('CONFIRME sur stockage simulé: deux commandes concurrentes consomment un code limité à une utilisation.');
let deleted = false;
prisma.priceEntry.deleteMany = async () => { deleted = true; return { count: 1 }; };
prisma.product.update = async () => { throw new Error('Foreign key constraint'); };
await assert.rejects(handler(productsRouter, 'put', '/:id')({ user, params: { id: 'p1' }, body: { prices: [{ storeId: 'missing', city: 'Rabat', price: 20 }] } }, response()), /Foreign key/);
assert.equal(deleted, true);
console.log('CONFIRME: suppression des prix exécutée avant une mise à jour qui échoue, sans transaction englobante.');
prisma.product.findFirst = async () => null;
prisma.brand.findFirst = async () => null;
prisma.product.findMany = async () => [{ id: 'farine-5kg', name: 'Farine Fleur 5kg' }];
const match = await matchProduct({ name: 'Farine Fleur 1kg', brand: 'Autre marque', ean: '1111111111111', weight: 1, unit: 'kg' });
assert.equal(match.productId, 'farine-5kg');
console.log('CONFIRME: matching fuzzy associe Farine Fleur 1kg à Farine Fleur 5kg malgré format différent.');
await prisma.$disconnect();
